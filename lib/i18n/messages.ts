export type MessageKey = keyof typeof messages.en;

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const table = messages[locale] || messages.en;
  let text: string = table[key] || messages.en[key] || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function pickLocalized(locale: Locale, en?: string | null, fr?: string | null) {
  if (locale === "fr") return (fr || en || "").trim();
  return (en || fr || "").trim();
}
